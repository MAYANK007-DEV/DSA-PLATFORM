import { Problem } from '../types/index.ts';
import { CORE_DSA_PROBLEMS, createCanonicalProblem } from './dsaProblems.ts';

// Helper to normalize title to slug/id
function slugify(title: string): string {
  return title
    .toLowerCase()
    .replace(/[()]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

// Map of existing core DSA problems by normalized slug for deduplication
const coreMap = new Map<string, Problem>();
for (const p of CORE_DSA_PROBLEMS) {
  coreMap.set(slugify(p.title), p);
  if (p.leetcodeSlug) {
    coreMap.set(p.leetcodeSlug, p);
  }
}

// Function to resolve or generate a canonical problem for company tracks
export function resolveCompanyProblem(
  title: string,
  difficulty: 'Easy' | 'Medium' | 'Hard',
  topic: string,
  pattern: string,
  company: 'Google' | 'Microsoft' | 'JPMorgan'
): Problem {
  const slug = slugify(title);
  const existing = coreMap.get(slug);
  if (existing) {
    // Add company evidence if not already present
    if (!existing.companyEvidence) {
      existing.companyEvidence = [];
    }
    if (!existing.companyEvidence.some((e) => e.company === company)) {
      existing.companyEvidence.push({
        company,
        verifiedDate: '2026-08-15',
        source: 'Community company-wise dataset (updated Aug 2026)',
      });
    }
    return existing;
  }

  // Create new canonical problem with verified LeetCode URL format
  const newProblem = createCanonicalProblem(
    `p-${slug}`,
    title,
    difficulty,
    topic,
    pattern,
    slug,
    undefined,
    [company]
  );
  coreMap.set(slug, newProblem);
  return newProblem;
}

